const INDEX = new Map<string, Term>();
for (const item of TERMS) {
  INDEX.set(item.term, item);
  for (const alias of item.aliases ?? []) if (!INDEX.has(alias)) INDEX.set(alias, item);
}

/** 依名詞或別名找條目；找不到回傳 undefined。 */
export function findTerm(name: string): Term | undefined {
  const key = name.trim();
  return INDEX.get(key) ?? INDEX.get(key.replace(/宮$/, ''));
}

/** 搜尋：名詞、別名或說明文字裡包含關鍵字的條目。空白關鍵字回傳全部。 */
export function searchTerms(query: string): Term[] {
  const keyword = query.trim();
  if (!keyword) return [...TERMS];
  const starts: Term[] = [];
  const contains: Term[] = [];
  for (const item of TERMS) {
    const names = [item.term, ...(item.aliases ?? [])];
    if (names.some((name) => name === keyword || name.startsWith(keyword))) starts.push(item);
    else if (names.some((name) => name.includes(keyword)) || item.text.includes(keyword)) contains.push(item);
  }
  return [...starts, ...contains];
}
